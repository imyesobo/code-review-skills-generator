import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CATEGORY_LABELS } from '../analyze/categories.js';
import type { Rule } from '../types.js';

export type Target = 'agents' | 'instructions' | 'skills';

export interface GenerateOptions {
  out: string;
  targets: Target[];
  instructionsDir: string;
  skillsDir: string;
  skillMinRules: number;
  minConfidence: number;
  dryRun: boolean;
}

export const DEFAULT_GENERATE: Omit<GenerateOptions, 'out'> = {
  targets: ['agents', 'instructions', 'skills'],
  instructionsDir: '.github/instructions',
  skillsDir: '.github/skills',
  skillMinRules: 2,
  minConfidence: 0,
  dryRun: false,
};

export const START = '<!-- code-review-skills-generator:start -->';
export const END = '<!-- code-review-skills-generator:end -->';

export interface GeneratedFile { path: string; content: string }

/**
 * Routing:
 *  - rules with an inferred applyTo glob        -> <instructionsDir>/<slug>.instructions.md
 *  - remaining rules whose category has >= N    -> <skillsDir>/<category>-review/SKILL.md
 *  - everything else (repo-wide, general)       -> AGENTS.md (managed section)
 * Disabled targets fall through to the next enabled one, ending at AGENTS.md.
 */
export function planFiles(allRules: Rule[], opts: GenerateOptions, existingAgents?: string): GeneratedFile[] {
  const rules = allRules.filter((r) => r.confidence >= opts.minConfidence);
  const has = (t: Target) => opts.targets.includes(t);
  const scoped = new Map<string, Rule[]>();
  const byCategory = new Map<string, Rule[]>();
  const general: Rule[] = [];

  for (const r of rules) {
    if (r.applyTo && has('instructions')) push(scoped, r.applyTo, r);
    else if (r.category !== 'general' && has('skills')) push(byCategory, r.category, r);
    else general.push(r);
  }
  for (const [cat, rs] of [...byCategory]) {
    if (rs.length < opts.skillMinRules) {
      general.push(...rs);
      byCategory.delete(cat);
    }
  }

  const files: GeneratedFile[] = [];
  for (const [glob, rs] of scoped) {
    files.push({ path: join(opts.instructionsDir, `${slugify(glob)}.instructions.md`), content: renderInstructions(glob, rs) });
  }
  for (const [cat, rs] of byCategory) {
    const name = `${cat}-review`;
    files.push({ path: join(opts.skillsDir, name, 'SKILL.md'), content: renderSkill(name, cat, rs) });
  }
  if (has('agents') || general.length) {
    files.push({ path: 'AGENTS.md', content: mergeManaged(existingAgents, renderAgentsSection(general, files)) });
  }
  return files;
}

export function writeFiles(rules: Rule[], opts: GenerateOptions): GeneratedFile[] {
  const agentsPath = join(opts.out, 'AGENTS.md');
  const existing = existsSync(agentsPath) ? readFileSync(agentsPath, 'utf8') : undefined;
  const files = planFiles(rules, opts, existing);
  if (!opts.dryRun) {
    for (const f of files) {
      const full = join(opts.out, f.path);
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, f.content);
    }
  }
  return files;
}

function push<K, V>(m: Map<K, V[]>, k: K, v: V) {
  const arr = m.get(k);
  if (arr) arr.push(v);
  else m.set(k, [v]);
}

export function slugify(s: string): string {
  return (
    s
      .replace(/\*\*\/?/g, '')
      .replace(/\{([^}]*)\}/g, (_, x: string) => x.replace(/,/g, '-'))
      .replace(/\*/g, '')
      .replace(/[^a-zA-Z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .toLowerCase() || 'all'
  );
}

const GENERATED_NOTE = '<!-- Generated by code-review-skills-generator from pull request reviews. Edit freely; re-running overwrites this file. -->';

function evidence(r: Rule): string {
  return `${r.support} comments · ${r.prs} PRs · ${r.reviewers} reviewers · confidence ${r.confidence}`;
}

function ruleBullets(rs: Rule[], withEvidence: boolean): string {
  return rs
    .map((r) => {
      const line = `- **${r.title}** — ${r.rule}`;
      return withEvidence ? `${line}\n  <!-- ${evidence(r)} -->` : line;
    })
    .join('\n');
}

export function renderInstructions(glob: string, rs: Rule[]): string {
  return `---
applyTo: "${glob}"
---
${GENERATED_NOTE}

# Review guidelines for \`${glob}\`

Reviewers repeatedly raised the following points on files matching this pattern. Follow them when writing or changing these files.

${ruleBullets(rs, true)}
`;
}

export function renderSkill(name: string, category: string, rs: Rule[]): string {
  const label = CATEGORY_LABELS[category] ?? category;
  const kws = [...new Set(rs.flatMap((r) => r.keywords))].slice(0, 8).join(', ');
  const total = rs.reduce((s, r) => s + r.support, 0);
  const description = `${label} conventions distilled from ${total} code review comments. Use when writing, refactoring or reviewing code that involves ${kws}.`;
  const examples = rs
    .flatMap((r) => r.examples.slice(0, 1).map((e) => `- ${r.title}: "${e.body.replace(/"/g, "'")}"${e.url ? ` ([source](${e.url}))` : ''}`))
    .join('\n');
  return `---
name: ${name}
description: ${JSON.stringify(description)}
---
${GENERATED_NOTE}

# ${label} review checklist

Apply this checklist before proposing or finalizing a change. Each item comes from recurring reviewer feedback.

${rs.map((r) => `- [ ] **${r.title}** — ${r.rule}${r.applyTo ? ` _(applies to \`${r.applyTo}\`)_` : ''}`).join('\n')}

## Examples from past reviews

${examples}
`;
}

export function renderAgentsSection(general: Rule[], others: GeneratedFile[]): string {
  const parts = [START, '## Code review conventions', '', '_Generated from recurring pull request review feedback._', ''];
  if (general.length) parts.push(ruleBullets(general, true), '');
  if (others.length) {
    parts.push('See also:', '', ...others.map((f) => `- \`${f.path}\``), '');
  }
  parts.push(END);
  return parts.join('\n');
}

/** Replace the managed section in an existing AGENTS.md, preserving everything else. */
export function mergeManaged(existing: string | undefined, section: string): string {
  if (!existing) return `# AGENTS.md\n\n${section}\n`;
  const s = existing.indexOf(START);
  const e = existing.indexOf(END);
  if (s >= 0 && e > s) return existing.slice(0, s) + section + existing.slice(e + END.length);
  return `${existing.replace(/\s*$/, '')}\n\n${section}\n`;
}
